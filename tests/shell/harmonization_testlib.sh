#!/usr/bin/env bash
# shellcheck disable=SC2034  # HT_* variables are consumed by the suites that source this file.
#
# Source-only fixture helpers for the desktop harmonization suites (plan F04.2).
# tests/run.sh never runs *_testlib.sh files; suites source this file.
#
# A suite that calls ht_fixture_init gets:
# - HOME, XDG_CONFIG_HOME, XDG_DATA_HOME, XDG_STATE_HOME, XDG_CACHE_HOME, XDG_RUNTIME_DIR and
#   TMPDIR inside one private directory that is removed on exit, together with tracked
#   background processes.
# - No host session: DBUS_SESSION_BUS_ADDRESS, WAYLAND_DISPLAY, HYPRLAND_INSTANCE_SIGNATURE,
#   DISPLAY and XDG_SESSION_ID are unset.
# - $HT_BIN first on PATH with stateful doubles for every host-facing command the shared
#   runtime uses (notify-send, pgrep, pkill, gsettings, busctl, dbus-send). Doubles record
#   their argv NUL-separated, keep state in $HT_STATE and never report an effect that they did
#   not record there, so a test asserts state rather than an echoed request.
#
# Evidence level: everything built on these doubles is argv or modeled-effect evidence
# (tests/fixtures/harmonization/README.md), never real-effect evidence.

HT_REPO_ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
HT_SESSION_VARS=(DBUS_SESSION_BUS_ADDRESS WAYLAND_DISPLAY HYPRLAND_INSTANCE_SIGNATURE DISPLAY XDG_SESSION_ID)
HT_BASH=${BASH:-/bin/bash}
HT_ROOT=""
HT_BIN=""
HT_STATE=""
HT_STATUS=0
HT_STDOUT=""
HT_STDERR=""
declare -ag HT_BACKGROUND_PIDS=()

# ---------------------------------------------------------------------------
# Reporting

ht_ok() {
    printf 'ok - %s\n' "$*"
}

ht_fail() {
    printf 'not ok - %s\n' "$*" >&2
    exit 1
}

# ---------------------------------------------------------------------------
# Isolation

ht_scrub_session_env() {
    unset "${HT_SESSION_VARS[@]}"
}

# ht_fixture_init: create the private fixture root and switch the environment into it.
ht_fixture_init() {
    HT_ROOT=$(mktemp -d "${TMPDIR:-/tmp}/hss-fixture.XXXXXX")
    trap ht_cleanup EXIT
    HT_BIN="$HT_ROOT/bin"
    HT_STATE="$HT_ROOT/doubles"
    export HOME="$HT_ROOT/home"
    export XDG_CONFIG_HOME="$HOME/.config"
    export XDG_DATA_HOME="$HOME/.local/share"
    export XDG_STATE_HOME="$HT_ROOT/state"
    export XDG_CACHE_HOME="$HT_ROOT/cache"
    export XDG_RUNTIME_DIR="$HT_ROOT/runtime"
    export TMPDIR="$HT_ROOT/tmp"
    export STUB_LOG="$HT_ROOT/stub.log"
    export HYPRLAND_SETUP_DIR="$HT_REPO_ROOT"
    mkdir -p -- "$HT_BIN" "$HT_STATE"/{calls,exit,stdout,gsettings,dbus} "$XDG_CONFIG_HOME" "$XDG_DATA_HOME" \
        "$XDG_STATE_HOME" "$XDG_CACHE_HOME" "$XDG_RUNTIME_DIR" "$TMPDIR" "$HT_ROOT/snapshots"
    chmod 700 "$XDG_RUNTIME_DIR"
    : > "$STUB_LOG"
    : > "$HT_STATE/procs"
    : > "$HT_STATE/signals"
    ht_scrub_session_env
    unset HSS_ROLES_FILE HSS_THEME_DIR HSS_SCRIPTS_DIR HSS_ACTION_NOTIFY HSS_THEME_VARIANT \
        HSS_HARMONIZATION_ADOPT DRY_RUN HSS_TEST_MODE STUB_INSTALLED
    export PATH="$HT_BIN:$HT_REPO_ROOT/tests/stubs:$PATH"
    ht_install_default_doubles
}

ht_track_pid() {
    HT_BACKGROUND_PIDS+=("$1")
}

ht_cleanup() {
    local pid
    for pid in "${HT_BACKGROUND_PIDS[@]}"; do
        kill "$pid" 2>/dev/null || true
        wait "$pid" 2>/dev/null || true
    done
    HT_BACKGROUND_PIDS=()
    if [[ -n $HT_ROOT && -d $HT_ROOT ]]; then
        chmod -R u+w -- "$HT_ROOT" 2>/dev/null || true
        rm -rf -- "$HT_ROOT"
    fi
}

# ht_restricted_path TOOL...: print a PATH value made of $HT_BIN and a directory holding only
# the named host tools. Used to model a missing executable without touching the host.
ht_restricted_path() {
    local dir tool found
    dir=$(mktemp -d "$HT_ROOT/sysbin.XXXXXX")
    for tool in "$@"; do
        found=$(PATH=${PATH#"$HT_BIN:"} command -v -- "$tool" 2>/dev/null) || continue
        [[ $found == /* ]] || continue
        ln -s -- "$found" "$dir/$tool"
    done
    printf '%s:%s\n' "$HT_BIN" "$dir"
}

