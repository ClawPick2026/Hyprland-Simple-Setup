# ht_run CMD...: run without tripping errexit; sets HT_STATUS and the HT_STDOUT/HT_STDERR files.
ht_run() {
    HT_STDOUT="$HT_ROOT/last.stdout"
    HT_STDERR="$HT_ROOT/last.stderr"
    HT_STATUS=0
    "$@" >"$HT_STDOUT" 2>"$HT_STDERR" || HT_STATUS=$?
}

assert_eq() {
    local expected=$1 actual=$2 label=${3:-value}
    [[ $expected == "$actual" ]] && return 0
    printf 'not ok - %s: expected [%s], got [%s]\n' "$label" "$expected" "$actual" >&2
    exit 1
}

assert_contains() {
    local haystack=$1 needle=$2 label=${3:-text}
    [[ $haystack == *"$needle"* ]] && return 0
    printf 'not ok - %s: [%s] does not contain [%s]\n' "$label" "$haystack" "$needle" >&2
    exit 1
}

assert_status() {
    assert_eq "$1" "$HT_STATUS" "${2:-exit status}"
}

# assert_json JSON_TEXT_OR_FILE FILTER [LABEL]: FILTER must produce true.
assert_json() {
    local input=$1 filter=$2 label=${3:-json}
    if [[ -f $input ]]; then
        jq -e "$filter" "$input" >/dev/null 2>&1 && return 0
        input=$(cat -- "$input")
    elif jq -e "$filter" <<<"$input" >/dev/null 2>&1; then
        return 0
    fi
    printf 'not ok - %s: %s failed for %s\n' "$label" "$filter" "$input" >&2
    exit 1
}

assert_calls() {
    assert_eq "$2" "$(ht_calls "$1")" "${3:-$1 invocation count}"
}

# assert_argv NAME INDEX ARG...: invocation INDEX of double NAME received exactly ARG....
assert_argv() {
    local name=$1 index=$2 file expected
    shift 2
    file="$HT_STATE/calls/$name.$index"
    expected="$HT_ROOT/expected-argv"
    if (($#)); then printf '%s\0' "$@"; fi > "$expected"
    if [[ ! -f $file ]] || ! cmp -s -- "$expected" "$file"; then
        printf 'not ok - %s call %s argv: expected [%s], got [%s]\n' "$name" "$index" \
            "$(tr '\0' '|' < "$expected")" "$( [[ -f $file ]] && tr '\0' '|' < "$file")" >&2
        exit 1
    fi
}

# ht_path_state PATH: one line describing PATH (type, link target or digest and mode).
ht_path_state() {
    local path=$1
    if [[ -L $path ]]; then
        printf 'link %s\n' "$(readlink -- "$path")"
    elif [[ -f $path ]]; then
        printf 'file %s %s\n' "$(sha256sum -- "$path" | cut -d' ' -f1)" "$(stat -c %a -- "$path")"
    elif [[ -d $path ]]; then
        printf 'dir\n'
    else
        printf 'missing\n'
    fi
}

ht__snapshot_key() {
    printf '%s' "$1" | sha256sum | cut -d' ' -f1
}

ht_snapshot() {
    local path
    for path in "$@"; do
        ht_path_state "$path" > "$HT_ROOT/snapshots/$(ht__snapshot_key "$path")"
    done
}

assert_file_unchanged() {
    local path=$1 label=${2:-$1} before after
    before=$(cat -- "$HT_ROOT/snapshots/$(ht__snapshot_key "$path")")
    after=$(ht_path_state "$path")
    [[ $before == "$after" ]] && return 0
    printf 'not ok - %s changed: before [%s], after [%s]\n' "$label" "$before" "$after" >&2
    exit 1
}

# ht_tree_listing DIR: sorted "relative-path state" lines for every file and symlink below DIR
# (symlinks are not followed). One process, so suites can snapshot large trees cheaply.
ht_tree_listing() {
    python3 -B - "$1" <<'PY'
import hashlib
import os
import sys

root = sys.argv[1]
if not os.path.isdir(root):
    print("missing")
    sys.exit(0)
rows = []
for base, dirs, files in os.walk(root):
    for name in dirs + files:
        path = os.path.join(base, name)
        relative = path[len(root):]
        if os.path.islink(path):
            rows.append(f"{relative} link {os.readlink(path)}")
        elif name in files and os.path.isfile(path):
            with open(path, "rb") as handle:
                digest = hashlib.sha256(handle.read()).hexdigest()
            rows.append(f"{relative} file {digest} {os.stat(path).st_mode & 0o777:o}")
for row in sorted(rows):
    print(row)
PY
}

ht_snapshot_tree() {
    ht_tree_listing "$1" > "$HT_ROOT/snapshots/tree-$(ht__snapshot_key "$1")"
}

assert_tree_unchanged() {
    local dir=$1 label=${2:-$1} changes
    if ! changes=$(diff -- "$HT_ROOT/snapshots/tree-$(ht__snapshot_key "$dir")" <(ht_tree_listing "$dir")); then
        printf 'not ok - %s changed:\n%s\n' "$label" "$changes" >&2
        exit 1
    fi
}

# ht_tree_changes DIR: print the relative paths that differ from the last ht_snapshot_tree.
ht_tree_changes() {
    local dir=$1
    diff -- "$HT_ROOT/snapshots/tree-$(ht__snapshot_key "$dir")" <(ht_tree_listing "$dir") \
        | sed -n 's/^[<>] \([^ ]*\) .*/\1/p' | LC_ALL=C sort -u
}

# ht_expect_failure CMD...: CMD (often an assertion) must fail in a subshell. Proves that an
# oracle notices a double that reports success without changing state.
ht_expect_failure() {
    if ( "$@" ) >/dev/null 2>&1; then
        printf 'not ok - expected failure from: %s\n' "$*" >&2
        exit 1
    fi
}

# ht_assert_user_lines_preserved BEFORE AFTER MANAGED_JSON TARGET [LABEL]
# Oracle for managed-keys and managed-region edits. Every original line that is not a managed
# key (per hss-theme managed.json for TARGET's canonical path) must survive in order, and every
# added line must be a managed key, a theme region line, a blank line or a new section header.
ht_assert_user_lines_preserved() {
    local before=$1 after=$2 managed=$3 target=$4 label=${5:-$4}
    python3 -B - "$before" "$after" "$managed" "$target" "$label" <<'PY' || exit 1
import json, os, re, sys

before_path, after_path, managed_path, target, label = sys.argv[1:6]
managed = json.load(open(managed_path, encoding="utf-8"))
canonical = os.path.realpath(target)
keys = set(managed.get("keys", {}).get(canonical, {}))


def classify(text):
    rows, section, region = [], None, False
    for line in text.splitlines():
        stripped = line.strip()
        if re.search(r">>> hss-theme:[a-z0-9_-]+ >>>", stripped):
            region = True
            rows.append((line, "region"))
            continue
        if re.search(r"<<< hss-theme:[a-z0-9_-]+ <<<", stripped):
            region = False
            rows.append((line, "region"))
            continue
        if region:
            rows.append((line, "region"))
            continue
        header = re.fullmatch(r"\[(.+)\]", stripped)
        if header:
            section = header.group(1)
            rows.append((line, "header"))
            continue
        match = re.match(r"^\s*([^=#;\s\[][^=]*?)\s*=", line)
        if match:
            name = match.group(1).strip()
            if (f"{section}/{name}" if section else name) in keys:
                rows.append((line, "managed"))
                continue
        rows.append((line, "blank" if not stripped else "user"))
    return rows


old = [row for row in classify(open(before_path, encoding="utf-8").read()) if row[1] not in ("managed", "region")]
new = classify(open(after_path, encoding="utf-8").read())
old_headers = {line for line, kind in old if kind == "header"}
index = 0
problems = []
for line, kind in new:
    if index < len(old) and kind != "managed" and kind != "region" and line == old[index][0]:
        index += 1
    elif kind in ("managed", "region", "blank") or (kind == "header" and line not in old_headers):
        continue
    else:
        problems.append(f"unexpected line {line!r}")
if index < len(old):
    problems.append(f"lost or reordered user line {old[index][0]!r}")
if problems:
    print(f"not ok - {label}: " + "; ".join(problems[:5]), file=sys.stderr)
    sys.exit(1)
PY
}

# ht_theme_apply SCRIPTS_DIR ARG...: run hss_theme_apply from providers/theme.sh in a child
# shell with the installer-side options (VARIANT [--adopt] [--preview] [--units LIST]).
# $HT_STDOUT receives {outcome, reason, report, run, observed, pending}; HT_STATUS is the exit.
ht_theme_apply() {
    local driver="$HT_ROOT/theme-driver.sh"
    if [[ ! -f $driver ]]; then
        cat > "$driver" <<'DRIVER'
#!/usr/bin/env bash
set -euo pipefail
export HSS_SCRIPTS_DIR=$1
shift
# shellcheck source=/dev/null
source "$HSS_SCRIPTS_DIR/lib/hss_runtime.sh"
# shellcheck source=/dev/null
source "$HSS_SCRIPTS_DIR/providers/theme.sh"
status=0
hss_theme_apply "$@" >&2 || status=$?
jq -cn --arg outcome "$HSS_OUTCOME" --arg reason "$HSS_REASON" --arg report "${HSS_THEME_REPORT:-}" \
    --arg run "${HSS_RUN_ID:-}" --arg observed "$HSS_OBSERVED" --arg pending "$HSS_PENDING" \
    '{outcome: $outcome, reason: $reason, report: $report, run: $run, pending: $pending,
      observed: (if $observed == "" then null else ($observed | fromjson) end)}'
exit "$status"
DRIVER
    fi
    ht_run "$HT_BASH" "$driver" "$@"
}
