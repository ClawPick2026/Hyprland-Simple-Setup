# Stateful doubles

# ht__write_double NAME < BODY: write a double whose shared header records the invocation.
ht__write_double() {
    local name=$1 path="$HT_BIN/$1"
    {
        printf '#!%s\n' "$HT_BASH"
        printf '# Stateful test double generated by tests/shell/harmonization_testlib.sh.\n'
        printf 'set -u\n'
        printf 'name=%q\n' "$name"
        printf 'state=%q\n' "$HT_STATE"
        cat <<'HEADER'
count_file="$state/calls/$name.count"
count=0
[[ -f $count_file ]] && count=$(<"$count_file")
count=$((count + 1))
printf '%s' "$count" > "$count_file"
if (($#)); then printf '%s\0' "$@"; fi > "$state/calls/$name.$count"
forced_exit=""
[[ -f $state/exit/$name ]] && forced_exit=$(<"$state/exit/$name")
emit_stdout() {
    local line
    [[ -f $state/stdout/$name ]] || return 0
    while IFS= read -r line || [[ -n $line ]]; do printf '%s\n' "$line"; done < "$state/stdout/$name"
}
HEADER
        cat
    } > "$path"
    chmod 755 "$path"
}

# ht_double NAME: a recorder that prints its configured stdout and exits with its configured code.
ht_double() {
    ht__write_double "$1" <<'BODY'
emit_stdout
exit "${forced_exit:-0}"
BODY
}

ht_double_exit() {
    printf '%s' "$2" > "$HT_STATE/exit/$1"
}

ht_double_stdout() {
    printf '%s\n' "$2" > "$HT_STATE/stdout/$1"
}

ht_remove_double() {
    rm -f -- "$HT_BIN/$1"
}

ht_calls() {
    local file="$HT_STATE/calls/$1.count"
    if [[ -f $file ]]; then
        cat -- "$file"
        printf '\n'
    else
        printf '0\n'
    fi
}

# ht_argv NAME INDEX: print one recorded argument per line (display only; compare with assert_argv).
ht_argv() {
    local file="$HT_STATE/calls/$1.$2"
    [[ -f $file ]] || return 1
    tr '\0' '\n' < "$file"
}

ht_proc_start() {
    printf '%s\n' "$1" >> "$HT_STATE/procs"
}

ht_proc_stop() {
    local tmp="$HT_STATE/procs.tmp" proc
    while IFS= read -r proc; do
        [[ $proc == "$1" ]] || printf '%s\n' "$proc"
    done < "$HT_STATE/procs" > "$tmp"
    mv -f -- "$tmp" "$HT_STATE/procs"
}

ht_signals() {
    cat -- "$HT_STATE/signals"
}

# ht_gsettings_seed SCHEMA KEY VALUE [readonly]: VALUE is stored in gsettings get format.
ht_gsettings_seed() {
    mkdir -p -- "$HT_STATE/gsettings/$1"
    printf '%s\n' "$3" > "$HT_STATE/gsettings/$1/$2"
    if [[ ${4:-} == readonly ]]; then
        : > "$HT_STATE/gsettings/$1/$2.readonly"
    fi
}

ht_gsettings_value() {
    cat -- "$HT_STATE/gsettings/$1/$2"
}

# ht_dbus_own NAME UNIQUE PID: make NAME owned on the modeled user bus.
ht_dbus_own() {
    printf '%s %s\n' "$2" "$3" > "$HT_STATE/dbus/$1"
}

ht_dbus_release() {
    rm -f -- "$HT_STATE/dbus/$1"
}

ht_install_default_doubles() {
    ht_double notify-send

    # procps-ng 4.0.7 semantics as used by the runtime: pgrep -u UID -x -- NAME.
    ht__write_double pgrep <<'BODY'
[[ -z $forced_exit ]] || exit "$forced_exit"
target="" exact=false
while (($#)); do
    case $1 in
        -u) shift; (($#)) && shift ;;
        -x) exact=true; shift ;;
        --) shift; target=${1-}; break ;;
        -*) shift ;;
        *) target=$1; break ;;
    esac
done
$exact || { printf 'pgrep double: only exact (-x) matching is modeled\n' >&2; exit 2; }
while IFS= read -r proc; do
    [[ $proc == "$target" ]] && exit 0
done < "$state/procs"
exit 1
BODY

    # pkill -u UID -x -SIGNAL -- NAME: records "NAME SIGNAL" only for a modeled running process.
    ht__write_double pkill <<'BODY'
[[ -z $forced_exit ]] || exit "$forced_exit"
target="" exact=false sig=TERM
while (($#)); do
    case $1 in
        -u) shift; (($#)) && shift ;;
        -x) exact=true; shift ;;
        --signal) shift; sig=${1-}; sig=${sig#SIG}; (($#)) && shift ;;
        --) shift; target=${1-}; break ;;
        -[A-Z]*|-[0-9]*) sig=${1#-}; sig=${sig#SIG}; shift ;;
        -*) shift ;;
        *) target=$1; break ;;
    esac
done
$exact || { printf 'pkill double: only exact (-x) matching is modeled\n' >&2; exit 2; }
while IFS= read -r proc; do
    if [[ $proc == "$target" ]]; then
        printf '%s %s\n' "$target" "$sig" >> "$state/signals"
        exit 0
    fi
done < "$state/procs"
exit 1
BODY

    # gsettings: writable prints true/false and exits 0 for a known key; set accepts an
    # unquoted string like the real tool and stores it in get format; unknown keys fail.
    ht__write_double gsettings <<'BODY'
[[ -z $forced_exit ]] || exit "$forced_exit"
command=${1-} schema=${2-} key=${3-}
file="$state/gsettings/$schema/$key"
case $command in
    writable)
        [[ -f $file ]] || { printf 'No such schema "%s"\n' "$schema" >&2; exit 1; }
        if [[ -f $file.readonly ]]; then printf 'false\n'; else printf 'true\n'; fi
        ;;
    get)
        [[ -f $file ]] || { printf 'No such key "%s"\n' "$key" >&2; exit 1; }
        printf '%s\n' "$(<"$file")"
        ;;
    set)
        [[ -f $file ]] || { printf 'No such key "%s"\n' "$key" >&2; exit 1; }
        [[ ! -f $file.readonly ]] || { printf 'The key is not writable\n' >&2; exit 1; }
        value=${4-}
        if [[ $value =~ ^-?[0-9]+$ || $value == true || $value == false || $value == "'"* ]]; then
            printf '%s\n' "$value" > "$file"
        else
            printf "'%s'\n" "$value" > "$file"
        fi
        ;;
    *) exit 1 ;;
esac
BODY

    # busctl --user call org.freedesktop.DBus /org/freedesktop/DBus org.freedesktop.DBus METHOD s NAME
    # Reply format observed with systemd 262: s ":1.42" and u 1234.
    ht__write_double busctl <<'BODY'
[[ -z $forced_exit ]] || exit "$forced_exit"
args=("$@") user=false method="" bus_name=""
for ((i = 0; i < ${#args[@]}; i++)); do
    case ${args[i]} in
        --user) user=true ;;
        GetNameOwner|GetConnectionUnixProcessID) method=${args[i]}; bus_name=${args[i + 2]-} ;;
    esac
done
$user || { printf 'busctl double: only the user bus is modeled\n' >&2; exit 1; }
record="$state/dbus/$bus_name"
if [[ -z $bus_name || ! -f $record ]]; then
    printf "Call failed: Could not get owner of name '%s': no such name\n" "$bus_name" >&2
    exit 1
fi
read -r unique pid < "$record"
case $method in
    GetNameOwner) printf 's "%s"\n' "$unique" ;;
    GetConnectionUnixProcessID) printf 'u %s\n' "$pid" ;;
    *) exit 1 ;;
esac
BODY

    # dbus-send --session --print-reply=literal ...; observed with dbus 1.16: a literal string
    # reply is "   VALUE" without a newline, a uint32 reply is "   uint32 VALUE".
    ht__write_double dbus-send <<'BODY'
[[ -z $forced_exit ]] || exit "$forced_exit"
session=false method="" bus_name=""
for arg; do
    case $arg in
        --session) session=true ;;
        org.freedesktop.DBus.GetNameOwner) method=GetNameOwner ;;
        org.freedesktop.DBus.GetConnectionUnixProcessID) method=GetConnectionUnixProcessID ;;
        string:*) bus_name=${arg#string:} ;;
    esac
done
$session || { printf 'dbus-send double: only the session bus is modeled\n' >&2; exit 1; }
record="$state/dbus/$bus_name"
if [[ -z $bus_name || ! -f $record ]]; then
    printf "Error org.freedesktop.DBus.Error.NameHasNoOwner: Could not get owner of name '%s'\n" "$bus_name" >&2
    exit 1
fi
read -r unique pid < "$record"
case $method in
    GetNameOwner) printf '   %s' "$unique" ;;
    GetConnectionUnixProcessID) printf '   uint32 %s\n' "$pid" ;;
    *) exit 1 ;;
esac
BODY
}

