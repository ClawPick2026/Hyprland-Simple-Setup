# ht_write_roles FILE [ROLE=PACKAGE[,MEMBER...]]...
# Writes schema-2 roles.json from packages.json like setup.sh:generate_roles_json. The first
# package is the primary; all listed packages are selected members. ROLE= selects None
# (roles.ROLE is null, selected.ROLE is empty). Unlisted roles use the registry default.
ht_write_roles() {
    local file=$1 spec='{}' item role packages
    shift
    for item in "$@"; do
        role=${item%%=*}
        packages=${item#*=}
        spec=$(jq -c --arg role "$role" --arg packages "$packages" \
            '.[$role] = ($packages | if . == "" then [] else split(",") end)' <<<"$spec")
    done
    mkdir -p -- "$(dirname -- "$file")"
    jq -e --argjson spec "$spec" --arg home "$HOME" '
        . as $registry
        | ($spec | keys - ($registry.roles | keys)) as $unknown_roles
        | if ($unknown_roles | length) > 0 then error("unknown roles: \($unknown_roles)") else . end
        | reduce ($registry.roles | keys_unsorted[]) as $role (
            {schema_version: 2, roles: {}, selected: {}, agent_executables: {}};
            (if ($spec | has($role)) then $spec[$role]
             elif $registry.roles[$role].default then [$registry.roles[$role].default]
             else [] end) as $packages
            | ($packages - [$registry.roles[$role].options[].package]) as $unknown
            | if ($unknown | length) > 0 then error("unknown \($role) packages: \($unknown)") else . end
            | .selected[$role] = [$registry.roles[$role].options[] | select(.package as $p | $packages | index($p))]
            | .roles[$role] = (if ($packages | length) == 0 then null
                               else ($registry.roles[$role].options[] | select(.package == $packages[0])) end))
        | walk(if type == "string" and startswith("{HOME}/") then $home + ltrimstr("{HOME}") else . end)
    ' "$HT_REPO_ROOT/packages.json" > "$file"
}

# ht_stow_fixture ENTRY...: copy dotfiles/.config/ENTRY into $HOME/dotfiles and link it from
# $HOME/.config the way GNU Stow does (a directory or file symlink into the dotfiles tree).
ht_stow_fixture() {
    local entry
    mkdir -p -- "$HOME/dotfiles/.config" "$XDG_CONFIG_HOME"
    for entry in "$@"; do
        cp -a -- "$HT_REPO_ROOT/dotfiles/.config/$entry" "$HOME/dotfiles/.config/$entry"
        ln -s -- "$HOME/dotfiles/.config/$entry" "$XDG_CONFIG_HOME/$entry"
    done
}

# ht_copy_runtime DEST: copy the shared runtime (dispatchers, lib/, providers/) and theme/
# into DEST/scripts and DEST/theme so a suite can add throwaway providers or registry entries.
ht_copy_runtime() {
    local dest=$1 source="$HT_REPO_ROOT/dotfiles/.config/hypr"
    mkdir -p -- "$dest/scripts"
    cp -a -- "$source/scripts/action_exec.sh" "$source/scripts/status_read.sh" "$dest/scripts/"
    cp -a -- "$source/scripts/lib" "$source/scripts/providers" "$dest/scripts/"
    ht_copy_theme "$dest/theme"
}

ht_copy_theme() {
    local dest=$1 source="$HT_REPO_ROOT/dotfiles/.config/hypr/theme"
    mkdir -p -- "$dest"
    cp -a -- "$source/." "$dest/"
    rm -rf -- "$dest/__pycache__"
}

